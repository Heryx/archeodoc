test("inferUSType rileva correttamente le forme archeologiche", () => {
  assert.equal(inferUSType(mockUSList[0], {}), "deposito");
  assert.equal(inferUSType(mockUSList[1], {}), "taglio");
  assert.equal(inferUSType(mockUSList[2], {}), "riempimento");
  assert.equal(
    inferUSType({ ...mockUSList[0], tipo: "USM", definizione: "Muro perimetrale" }, {}),
    "struttura",
  );
});

test("buildMatrixGraph estrae nodi, relazioni e livelli stratigrafici corretti", () => {
  const graph = buildMatrixGraph(mockUSList, "fisica");
  assert.equal(graph.nodes.length, 4);

  // US 1 covers US 2, US 3
  const copreEdges = graph.edges.filter((e) => e.type === "copre");
  assert.ok(copreEdges.length >= 2);

  // US 2 cuts US 4
  const tagliaEdge = graph.edges.find((e) => e.type === "taglia");
  assert.ok(tagliaEdge);
  assert.equal(tagliaEdge.from, "US2");
  assert.equal(tagliaEdge.to, "US4");

  // US 3 fills US 2
  const riempieEdge = graph.edges.find((e) => e.type === "riempie");
  assert.ok(riempieEdge);
  assert.equal(riempieEdge.from, "US3");
  assert.equal(riempieEdge.to, "US2");

  // US 1 is at top (higher layer number, smaller y coordinate)
  const node1 = graph.nodes.find((n) => n.key === "US1");
  const node4 = graph.nodes.find((n) => n.key === "US4");
  assert.ok(node1 && node4);
  assert.ok(node1.y < node4.y, "US 1 (superiore) deve essere posizionata più in alto rispetto a US 4");
});

test("exportHarrisMatrixSvg genera SVG vettoriale valido con cartiglio e legenda", () => {
  const svg = exportHarrisMatrixSvg(mockCantiere, mockUSList, "fisica");
  assert.ok(svg.includes("<svg"), "Deve contenere il tag <svg");
  assert.ok(svg.includes("HARRIS MATRIX"), "Deve contenere il titolo HARRIS MATRIX");
  assert.ok(svg.includes("SCAV-2026"), "Deve contenere il codice cantiere");
  assert.ok(svg.includes("FORME US"), "Deve contenere la legenda delle forme");
  assert.ok(svg.includes("RELAZIONI"), "Deve contenere la legenda delle relazioni");
  assert.ok(svg.includes("US 1") || svg.includes("US1"), "Deve contenere i nodi US");
});

